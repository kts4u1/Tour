/** 오늘이 속한 달을 기준으로 예시 행사 날짜를 만듭니다. */
export function buildDemoFestivals(today) {
  const year = Number(today.slice(0, 4));
  const month = Number(today.slice(4, 6));
  return FESTIVALS.map(([title, addr, lat, lng, monthOffset, day, length], i) => {
    const ym = shiftMonth(year, month, monthOffset);
    const range = monthRange(ym.year, ym.month);
    const lastDay = Number(range.end.slice(6));
    const start = range.start.slice(0, 6) + String(Math.min(day, lastDay)).padStart(2, '0');
    return {
      id: String(910001 + i),
      typeId: '15',
      title,
      addr,
      region: regionFromAddress(addr) || '기타',
      lat,
      lng,
      image: null,
      thumb: null,
      tel: null,
      start,
      end: addDays(start, length - 1),
    };
  });
}
